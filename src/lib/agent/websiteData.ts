export type WebsiteResult = { action: string; data: any };
export type ChatAction = Pick<WorkItem, 'id' | 'department' | 'title' | 'reason' | 'href'>;
export function websiteActions(results: WebsiteResult[]): ChatAction[] {
  return results.flatMap(({ action, data }) => action === 'worklist' ? data.tasks : action === 'briefing' ? data.tasks.priorities.tasks : [])
    .map(({id, department, title, reason, href}) => ({id, department, title, reason, href}));
}
const n = (v: number) => Number(v || 0).toLocaleString('id-ID');
const rp = (v: number) => `Rp ${n(v)}`;
const safe = (v: unknown) => String(v ?? '-').replace(/[\r\n]/g, ' ').replace(/[\\`*_\[\]<>|]/g, '\\$&');

const link = (label: string, href?: string) => href ? `[${label}](${href})` : '';
const displayNumber = (number: string, href?: string) => href ? link(safe(number), href) : safe(number);
function progress(lines: any[], requested: string, completed: string, verb: string) {
  const list = lines.slice(0, 10).map(line => `${safe(line.productSku)} ${n(line[completed])}/${n(line[requested])} ${verb}${line.rejectedQty ? ` (${n(line.rejectedQty)} ditolak)` : ''}`);
  return list.join('; ') + (lines.length > 10 ? '; lihat dokumen untuk baris lainnya' : '');
}

/** Figures are formatted from successful server reads, never generated by a model. */
export function websiteReply(results: WebsiteResult[]): string {
  return results.map(({action, data:d}) => {
    if (action === 'financial_summary') return financialReply([d]);
    if (action === 'inventory') {
      const unit = d.products[0]?.unit;
      const sameUnit = unit && !d.hasMore && d.products.every((product: any) => product.unit === unit);
      const totals = sameUnit ? ` Total stok fisik **${n(d.totals.onHand)}**, dipesan **${n(d.totals.reserved)}**, tersedia **${n(d.totals.available)}** (${safe(unit)}).` : '';
      const rows = d.products.map((product: any) => {
        const levels = product.stockLevels.map((stock: any) => `  - ${safe(stock.locationName)} (${safe(stock.locationCode)}): fisik ${n(stock.onHand)}, dipesan ${n(stock.reserved)}, tersedia ${n(stock.available)} ${safe(product.unit)}.`).join('\n');
        return `- **${safe(product.sku)} · ${safe(product.name)}** · harga jual ${rp(product.salesPrice)}\n${levels || '  - Belum ada lokasi aktif dalam cakupan akun.'}`;
      });
      return `**Stok produk** · ${safe(d.location)}\n\n${d.totalProducts} produk sesuai pencarian.${totals}\n\n${rows.join('\n') || 'Tidak ada produk yang sesuai.'}${d.hasMore ? `\n\nMenampilkan ${rows.length} dari ${d.totalProducts} produk.` : ''}\n\nSumber: [Stok & ketersediaan](/inventory/products).`;
    }
    if (action === 'contacts') return `**${d.type === 'VENDOR' ? 'Vendor' : d.type === 'CUSTOMER' ? 'Pelanggan' : 'Pelanggan & vendor'}** · total ${n(d.totalCount)}\n\n${d.contacts.map((c:any)=>`- ${safe(c.id)} · **${safe(c.name)}** · ${safe(c.city)} · ${safe(c.type)}`).join('\n') || 'Tidak ada kontak yang sesuai.'}${d.hasMore ? `\n\nDaftar dibatasi ${d.contacts.length} dari ${d.totalCount} kontak.` : ''}\n\nSumber: [Pelanggan & vendor](/sales/contacts${d.type==='VENDOR'?'?type=vendors':d.type==='CUSTOMER'?'?type=customers':''}).`;
    if (action === 'sales_orders' || action === 'purchase_orders') {
      const purchase = action === 'purchase_orders';
      const title = purchase ? 'Pesanan pembelian' : 'Pesanan penjualan';
      const rows = d.orders.map((order: any) => [
        `- **${displayNumber(order.orderNumber || order.poNumber, order.href)}**`,
        safe(order.contact?.name || order.vendor?.name), safe(statusLabel(order.status)),
        order.totalGross !== undefined || order.total !== undefined ? rp(order.totalGross ?? order.total) : '',
        progress(order.lines || [], purchase ? 'orderedQty' : 'quantity', purchase ? 'receivedQty' : 'deliveredQty', purchase ? 'diterima' : 'dikirim'),
      ].filter(Boolean).join(' · '));
      return `**${title}** · total ${n(d.totalCount)}\n\n${rows.join('\n') || (d.reference ? `Dokumen ${safe(d.reference)} tidak ditemukan pada cakupan pencarian ini.` : 'Belum ada pesanan yang sesuai.')}${d.hasMore ? `\n\nMenampilkan ${rows.length} dari ${d.totalCount} pesanan.` : ''}`;
    }
    if (action === 'invoices') {
      const title = d.overdueOnly ? 'Invoice pelanggan lewat jatuh tempo' : d.outstandingOnly ? 'Invoice pelanggan belum lunas dan sudah diposting' : 'Invoice pelanggan · semua status';
      const rows = d.invoices.map((invoice: any) => `- **${displayNumber(invoice.invoiceNumber, invoice.href)}** · ${safe(invoice.customer.name)} · ${safe(statusLabel(invoice.status))} · jatuh tempo ${safe(invoice.dueDate || 'belum ditetapkan')} · total ${rp(invoice.totalGross)}, sisa ${rp(invoice.outstandingAmount)}`);
      const issuePeriod = d.contextArgs?.start || d.contextArgs?.end
        ? `\n\nTanggal terbit invoice ${d.contextArgs.start || 'awal pencatatan'} sampai ${d.contextArgs.end || 'sekarang'} (WIB).`
        : '';
      return `**${title}** · total ${n(d.totalCount)}${issuePeriod}\n\n${rows.join('\n') || (d.reference ? `Invoice ${safe(d.reference)} tidak ditemukan pada cakupan pencarian ini.` : 'Tidak ada invoice yang sesuai.')}${d.hasMore ? `\n\nMenampilkan ${rows.length} dari ${d.totalCount} invoice.` : ''}\n\nSumber: [Invoice](/accounting/invoices).`;
    }
    if (action === 'dashboard_summary') return `**Ringkasan dashboard perusahaan**\n\n- Stok fisik: ${n(d.inventory.totalUnits)} unit\n- Stok tersedia: ${n(d.inventory.availableUnits)} unit\n- Valuasi persediaan: ${rp(d.inventory.totalValuation)}\n- Kas & bank: ${rp(d.bank.balance)}\n- Piutang usaha: ${rp(d.receivables.totalAR)}\n- Utang usaha: ${rp(d.payables.totalAP)}\n- PBJT terutang: ${rp(d.tax.balance)}\n- Penjualan bersih POS: ${rp(d.pos.revenue)} dari ${n(d.pos.ordersCount)} transaksi\n- Pesanan penjualan terkonfirmasi: ${n(d.sales.confirmedOrdersCount)}\n- Pesanan pembelian terkonfirmasi: ${n(d.purchase.confirmedOrdersCount)}\n- Peluang penjualan: ${n(d.crm.leadsCount)} senilai ${rp(d.crm.leadsValue)}\n\nSumber: [Dashboard eksekutif](/dashboard), posisi berjalan seluruh tanggal. Nilai peluang dan pesanan belum sama dengan pendapatan terposting.`;
    if (action === 'records') {
      const rows = d.records.map((record: any) => [
        `- **${displayNumber(record.reference, record.href)}**`, record.name && safe(record.name), safe(statusLabel(record.status)),
        record.location && safe(record.location),
        record.total !== undefined && `total ${rp(record.total)}, sisa ${rp(record.outstanding)}`,
        record.lines?.length && (record.lines[0].acceptedQty !== undefined
          ? progress(record.lines, 'demandQty', 'acceptedQty', 'diterima')
          : progress(record.lines, 'orderedQty', 'deliveredQty', 'dikirim')),
      ].filter(Boolean).join(' · '));
      return `**${safe(d.title)}** · total ${n(d.totalCount)}\n\n${rows.join('\n') || (d.reference ? `Dokumen ${safe(d.reference)} tidak ditemukan pada cakupan pencarian ini.` : 'Belum ada dokumen yang sesuai.')}${d.hasMore ? `\n\nMenampilkan ${rows.length} dari ${d.totalCount} dokumen.` : ''}`;
    }
    if (action === 'restock_plan') return `**Rencana pengisian stok** · ${safe(d.location)}\n\nAsumsi: stok tersedia di bawah ${n(d.planningAssumption.threshold)}, target ${n(d.planningAssumption.target)}, horizon ${n(d.planningAssumption.horizonDays)} hari.\n\n${d.items.map((r:any)=>`- **${safe(r.sku)} · ${safe(r.name)}**: tersedia ${n(r.available)}, rencana penerimaan ${n(r.openPurchaseQty)}, usulan pembelian ${n(r.suggestedQty)} unit.`).join('\n') || 'Tidak ada produk di bawah ambang.'}\n\n${n(d.matched)} produk sesuai ambang; rincian ditampilkan ${d.items.length}. Usulan belum disimpan menjadi pesanan.`;
    if (action === 'pos_sessions') return `**Sesi kasir** · ${safe(d.scope)}\n\n${d.sessions.map((s:any)=>`- ${safe(s.sessionCode)} · ${safe(s.cashier.name)} · ${safe(s.status)} · ${n(s.totalOrders)} transaksi · penjualan ${rp(s.totalSales)}`).join('\n') || 'Belum ada sesi kasir.'}\n\nSumber: [Kasir POS](/pos). Daftar sesi terbaru, bukan total seluruh penjualan perusahaan.`;
    if (action === 'worklist' || action === 'briefing') {
      const worklist = action === 'briefing' ? d.tasks.priorities : d;
      return worklist.tasks.length ? '**Prioritas pekerjaan** · Pilih tugas untuk membuka dokumennya.' : '**Prioritas pekerjaan**\n\nTidak ada tindak lanjut terdeteksi saat ini.';
    }
    if (action === 'sop') return d.guides.map((g:any)=>`**${safe(g.title)}**\n\n${safe(g.text)}`).join('\n\n');
    return '';
  }).filter(Boolean).join('\n\n---\n\n');
}

export function questionPeriod(message: string): {start:string;end:string} | undefined {
  const text = message.toLowerCase();
  const dates = text.match(/\b\d{4}-\d{2}-\d{2}\b/g);
  if (dates) return {start:dates[0],end:dates[1] || dates[0]};
  const today = businessDate();
  if (/hari ini|kemarin/.test(text)) {
    const day = /kemarin/.test(text) ? new Date(Date.parse(today+'T12:00:00+07:00')-86400000) : new Date(today+'T12:00:00+07:00');
    return {start:businessDate(day),end:businessDate(day)};
  }
  const months = ['januari','februari','maret','april','mei','juni','juli','agustus','september','oktober','november','desember'];
  const namedDays = [...text.matchAll(new RegExp('\\b(\\d{1,2})\\s+(' + months.join('|') + ')(?:\\s+(20\\d{2}))?', 'g'))];
  if (namedDays.length) {
    const year = text.match(/\b20\d{2}\b/)?.[0] || today.slice(0,4);
    const day = (m:RegExpMatchArray) => `${m[3]||year}-${String(months.indexOf(m[2])+1).padStart(2,'0')}-${m[1].padStart(2,'0')}`;
    return {start:day(namedDays[0]),end:day(namedDays[1]||namedDays[0])};
  }
  const month = months.findIndex(m=>text.includes(m));
  const year = Number(text.match(/\b20\d{2}\b/)?.[0] || today.slice(0,4));
  if (month >= 0 || /bulan (ini|lalu|kemarin)/.test(text)) {
    const d = new Date(Date.UTC(year, month >= 0 ? month : Number(today.slice(5,7))-1-(/bulan (lalu|kemarin)/.test(text)?1:0),1));
    const start=d.toISOString().slice(0,10), end=new Date(Date.UTC(d.getUTCFullYear(),d.getUTCMonth()+1,0)).toISOString().slice(0,10);
    return {start,end:start.slice(0,7)===today.slice(0,7)?today:end};
  }
  if (/tahun/.test(text)) { const y=year-(/tahun (lalu|kemarin)/.test(text)?1:0);return {start:`${y}-01-01`,end:y===Number(today.slice(0,4))?today:`${y}-12-31`}; }
  return undefined;
}

const documentPatterns = [
  { action: 'sales_orders', pattern: /\b(?:S\d+|SO[-/][A-Z0-9/-]*\d)\b/gi },
  { action: 'purchase_orders', pattern: /\b(?:P\d+|PO[-/][A-Z0-9/-]*\d)\b/gi },
  { action: 'invoices', pattern: /\bINV(?:[-/][A-Z0-9/-]*\d|\d+)\b/gi },
  { action: 'records', kind: 'vendor_bills', pattern: /\bBILL[-/][A-Z0-9/-]*\d\b/gi },
  { action: 'records', kind: 'deliveries', pattern: /\bWH\/OUT\/\d+\b/gi },
  { action: 'records', kind: 'receipts', pattern: /\bWH\/IN\/\d+\b/gi },
  { action: 'records', kind: 'transfers', pattern: /\bWH\/INT\/\d+\b/gi },
] as const;

function mentions(text: string, value: string) {
  const escaped = value.toLowerCase().replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return !!escaped && new RegExp(`(?<![\\p{L}\\p{N}-])${escaped}(?![\\p{L}\\p{N}-])`, 'u').test(text);
}

const stockWords = /\b(stok|stock|persediaan|produk|sku|menu|harga jual|stoknya)\b/;
const followUpWords = /\b(yang tadi|seperti tadi|cek lagi|cek ulang|ulang(i)?|yang sama|kalau|bagaimana dengan|sekarang berapa|berapa sekarang|stoknya|hppnya|invoice itu|dokumennya)\b/;
const financialWords = /\b(laba|rugi|untung|keuntungan|pendapatan|omzet|omset|beban|hpp|hppnya|laporan keuangan)\b/;
const overdueWords = /\b(lewat(?: jatuh)? tempo|terlambat|telat|overdue)\b/;
const outstandingWords = /\b(belum lunas|belum dibayar|masih harus ditagih|outstanding)\b/;
type Intent = { action: string; args: Record<string, unknown> };

/** Resolve common factual reads before asking the language model to plan anything. */
export async function answerWebsiteQuestion(
  ctx: AgentContext,
  message: string,
  page?: {path:string;resource?:string;document?:{reference:string}} | null,
  previous?: VerifiedRead | null,
) {
  const text = message.toLowerCase();
  if (/\b(buat|siapkan|simpan|ubah|hapus|konfirmasi|posting|bayar|kirim)\b/.test(text) && /\b(draft|quotation|rfq|transfer|pesanan|order|invoice|dokumen|penawaran|pembelian)\b/.test(text)) return null;
  if (/\b(cara|panduan|langkah|apa itu|jelaskan arti)\b/.test(text) && !/\b(tindak lanjut|prioritas|pekerjaan)\b/.test(text)) return null;
  const period = questionPeriod(message);
  const followUp = followUpWords.test(text) || (previous?.action === 'inventory' && /^(?:(?:di|ke)\s+)?(?:wh-|cafe-|gerai |gudang |outlet |kafe )/.test(text)) || /\b(yang (telat|terlambat|lewat tempo|belum lunas)|bulan (ini|lalu) saja)\b/.test(text);
  const intents: Intent[] = [];
  const referringToPrevious = followUp && /\b(yang tadi|yang sama|itu|dokumennya|cek lagi|cek ulang)\b/.test(text);
  const priorArgs = (action: string) => referringToPrevious && previous?.action === action ? previous.args : {};
  const respond = (reply: string) => ({ reply, toolsUsed: [] as string[], proposals: [], asOf: new Date().toISOString(), conversation: undefined });
  const fromPage = /\b(data ini|halaman ini|data di sini|dokumen ini)\b/.test(text) ? page?.document?.reference : undefined;
  const references = (referenceText: string) => documentPatterns.flatMap(doc =>
    [...new Set((referenceText.match(doc.pattern) ?? []).map(value => value.toUpperCase()))].map(reference => ({
      action: doc.action, args: { reference, limit: 1, ...('kind' in doc ? { kind: doc.kind } : {}),
        ...period, ...(doc.action === 'invoices' ? { overdueOnly: overdueWords.test(text), outstandingOnly: outstandingWords.test(text) } : {}) },
    })));
  const documents = stockWords.test(text) && !/\b(invoice|faktur|dokumen|po|so|pesanan|penerimaan|pengiriman)\b/.test(text)
    ? []
    : references(message);
  if (!documents.length && fromPage) documents.push(...references(fromPage));
  if (documents.length > 4) return respond('Sebutkan maksimal empat nomor dokumen per pertanyaan.');
  intents.push(...documents);
  if (!documents.length && (financialWords.test(text) || previous?.action === 'financial_summary' && followUp && !stockWords.test(text) && !/\b(invoice|faktur|tagihan|pesanan|penerimaan|pengiriman|vendor|pelanggan|kasir|prioritas)\b/.test(text))) {
    if (/\b(per (menu|sku|produk|outlet|lokasi|cabang)|di (outlet|gerai|cabang|kafe|gudang)|(?:wh|cafe)-[a-z0-9]+)\b/.test(text)) {
      return respond('Ringkasan keuangan dari jurnal tersedia untuk seluruh outlet perusahaan aktif. Sebutkan periode untuk melihat HPP dan laba rugi perusahaan.');
    }
    intents.push({ action: 'financial_summary', args: period ?? (followUp && previous?.action === 'financial_summary' ? previous.args : {}) });
  }
  if (!documents.length && !intents.length && (stockWords.test(text) || followUp && previous?.action === 'inventory')) {
    const products = await ctx.db.productVariant.findMany({ where: { archivedAt:null }, select: { sku:true, name:true } });
    const permitted = await permittedInventoryLocations(ctx);
    const locations = await ctx.db.warehouseLocation.findMany({
      where: { archivedAt: null, ...(permitted ? { code: { in: permitted } } : {}) },
      select: { code: true, name: true },
    });
    const explicitSkus = products.filter(product => mentions(text, product.sku)).map(product => product.sku);
    const nameMatches = products.filter(product => mentions(text, product.name));
    const matchingNames = nameMatches.filter(product => !nameMatches.some(other =>
      other.name.length > product.name.length && mentions(other.name.toLowerCase(), product.name)));
    const skus = [...new Set([...explicitSkus, ...matchingNames.map(product => product.sku)])];
    const mentionedLocations = locations.filter(location => mentions(text, location.code) || mentions(text, location.name));
    const aliases = /\b(?:di|ke)\s+(?:gerai|outlet|kafe|cafe)\b/.test(text) ? locations.filter(location => /gerai|outlet|kafe|cafe/i.test(location.name + ' ' + location.code))
      : /\b(?:di|ke)\s+gudang\b/.test(text) ? locations.filter(location => /gudang|^WH-/i.test(location.name) || /^WH-/.test(location.code)) : [];
    if (!mentionedLocations.length && aliases.length > 1) return respond(`Lokasi mana yang dimaksud? ${aliases.map(location => safe(location.name) + ' (' + safe(location.code) + ')').join(', ')}.`);
    const allLocations = /\bsemua lokasi\b/.test(text);
    const requested = allLocations ? [] : (mentionedLocations.length ? mentionedLocations : aliases).map(location => location.code);
    const unknownCode = [...message.matchAll(/\b(?:WH|CAFE)-[A-Z0-9]+\b/gi)].map(match => match[0].toUpperCase()).find(code => !locations.some(location => location.code === code));
    if (unknownCode) return respond(`Lokasi ${safe(unknownCode)} tidak tersedia dalam cakupan akun Anda. Sebutkan lokasi yang dapat Anda akses.`);
    if (followUp && !allLocations && !requested.length && /\b(?:kalau|bagaimana)\s+(?:di|ke)\b/.test(text)) {
      return respond('Lokasi mana yang dimaksud? Sebutkan nama atau kode lokasi, misalnya WH-JKT.');
    }
    const quoted = message.match(/["“]([^"”]{1,100})["”]/)?.[1];
    const token = [...message.matchAll(/\b[A-Z][A-Z0-9]*(?:-[A-Z0-9]+)+\b/g)].map(match => match[0]).find(code => !locations.some(location => location.code === code));
    const keyword = message.match(/\b(?:produk|menu|kopi)\s+([\p{L}\p{N}-]+(?:\s+[\p{L}\p{N}-]+)?)/iu)?.[1];
    const productWord = [...new Set(products.flatMap(product => product.name.toLowerCase().match(/[\p{L}]{4,}/gu) || []))]
      .filter(word => mentions(text, word)).sort((a,b) => b.length-a.length)[0];
    const query = skus.length ? undefined : quoted || token || productWord || (keyword && !/^(apa|yang|di|dan|saya|ini|ada|berapa|terdaftar|terbaru|tersedia|paling|rendah|website|perusahaan|semua|total)\b/i.test(keyword) ? keyword : undefined);
    const inherited = followUp && previous?.action === 'inventory' ? previous.args : {};
    const context = skus.length || query ? {} : { skus: inherited.skus, query: inherited.query };
    const selectedLocations = allLocations ? undefined : requested.length ? requested : inherited.locations;
    if (skus.length > 10 || requested.length > 10) return respond('Pilih maksimal sepuluh SKU dan sepuluh lokasi per pertanyaan.');
    const restock = /restock|stok rendah|stok menipis|isi ulang/.test(text) && !/berapa stok/.test(text);
    if (restock && (skus.length > 1 || requested.length > 1)) return respond('Untuk rencana isi ulang, pilih satu lokasi dan satu SKU, atau sebutkan satu lokasi untuk semua SKU.');
    intents.push(restock
      ? { action:'restock_plan', args:{ query:skus[0] ?? query, location:requested[0], limit:10 } }
      : { action:'inventory', args:{ ...context, ...(skus.length ? { skus } : query ? { query } : {}), locations:selectedLocations, limit:10 } });
  }
  if (!documents.length && /\b(dashboard|kas|bank|piutang|utang|hutang|pbjt)\b/.test(text) && !/\b(invoice|faktur)\b/.test(text)) intents.push({action:'dashboard_summary',args:{}});
  if (!documents.length && /\b(invoice|faktur|tagihan pelanggan)\b/.test(text)) intents.push({
    action:'invoices',args:{
      overdueOnly:false, outstandingOnly:false, limit:10, ...priorArgs('invoices'), ...period,
      ...(overdueWords.test(text) ? { overdueOnly:true, outstandingOnly:true } : outstandingWords.test(text) ? { overdueOnly:false, outstandingOnly:true } : {}),
    },
  });
  if (!documents.length && /\b(pesanan penjualan|sales order|penjualan|so)\b/.test(text) && !intents.some(intent => ['financial_summary','invoices'].includes(intent.action))) intents.push({action:'sales_orders',args:{limit:10,...priorArgs('sales_orders'),...period}});
  if (!documents.length && /\b(pesanan pembelian|purchase order|pembelian|po)\b/.test(text)) intents.push({action:'purchase_orders',args:{limit:10,...priorArgs('purchase_orders'),...period}});
  if (!documents.length && /\b(pelanggan|customer|vendor|pemasok|kontak)\b/.test(text) && !/invoice|tagihan|pesanan|order/.test(text)) intents.push({action:'contacts',args:{type:/vendor|pemasok/.test(text)?'VENDOR':/pelanggan|customer/.test(text)?'CUSTOMER':undefined,limit:10}});
  if (!documents.length && /\b(sesi kasir|sesi pos|transaksi kasir)\b/.test(text)) intents.push({action:'pos_sessions',args:{limit:10}});
  const kind = /tagihan vendor|vendor bill|bill vendor/.test(text)?'vendor_bills':/pengiriman|surat jalan|delivery/.test(text)?'deliveries':/penerimaan|goods receipt/.test(text)?'receipts':/transfer gudang|transfer stok/.test(text)?'transfers':/crm|prospek|peluang/.test(text)?'leads':null;
  if (!documents.length && kind) {
    const previousRecord = priorArgs('records');
    intents.push({action:'records',args:{limit:10,...(previousRecord.kind === kind ? previousRecord : {}),kind,...period}});
  }
  if (!intents.length && /\b(briefing|prioritas|pekerjaan|tindak lanjut|kondisi|data website|data perusahaan)\b/.test(text)) intents.push({action:'worklist',args:{limit:10}});
  if (!intents.length && /\b(data ini|halaman ini|data di sini)\b/.test(text)) {
    const action=page?.path==='/sales/contacts'?'contacts':page?.path==='/inventory/products'?'inventory':page?.path==='/accounting/invoices'?'invoices':page?.path==='/dashboard'?'dashboard_summary':null;
    if(action)intents.push({action,args:{limit:10,...(action==='contacts'?{type:page?.resource==='vendors'?'VENDOR':'CUSTOMER'}:{})}});
  }
  if (!intents.length && followUp && previous) {
    const filter = previous.action === 'invoices'
      ? overdueWords.test(text) ? { overdueOnly: true, outstandingOnly: true } : outstandingWords.test(text) ? { overdueOnly: false, outstandingOnly: true } : {}
      : {};
    intents.push({ action: previous.action, args: { ...previous.args, ...period, ...filter } });
  }
  if (!intents.length && followUp && /\b(yang tadi|kalau di|cek lagi|cek ulang|sekarang berapa|berapa sekarang)\b/.test(text)) {
    return respond('Data mana yang ingin diperiksa ulang? Sebutkan SKU dan lokasi, nomor dokumen, atau periode laporan.');
  }
  if (!intents.length) return null;
  const allowed = actionsFor(ctx.user.role);
  const results: WebsiteResult[] = [];
  const denied: string[] = [];
  for (const intent of intents.slice(0,4)) {
    if (!allowed.includes(intent.action)) { denied.push(intent.action); continue; }
    results.push({ action:intent.action, data:await dispatchAgentTool(ctx,intent.action,intent.args) });
  }
  const company = getCompanyById(ctx.companyId).name;
  return {
    reply: `**${safe(company)}**\n\n${websiteReply(results)}${denied.length ? '\n\nSebagian data yang diminta tidak tersedia untuk role Anda.' : ''}`,
    toolsUsed: results.map(result => result.action), proposals: [], actions: websiteActions(results), asOf: new Date().toISOString(), conversation: verifiedRead(results),
  };
}
